"""Definicion de los diagramas de actividad con carriles de CU1-CU8.

Cada caso es un diccionario con:
  clave, titulo
  carriles: [(nombre, ancho)] de izquierda a derecha
  nodos:    [(id, tipo, x, y, texto)]; x, y = centro en coordenadas absolutas.
            tipo: ini (inicio), fin (final), acc (accion), dec (decision o fusion),
            bar (bifurcacion/union; el "texto" es el ancho de la barra).
            En las acciones, "\\n" parte la linea.
  aristas:  [(origen, destino, guarda, opciones)]
            opciones: s / t = lado de salida / llegada (t, b, l, r; por omision b -> t),
            ym = altura del tramo horizontal (b -> t), xm = abscisa del tramo vertical (l/r -> l/r),
            pts = puntos intermedios explicitos, gp = esquina sup. izq. de la guarda,
            gdx / gdy = desplazamiento de la guarda.
Los flujos siguen el entregable 01 (Escenarios de los casos de uso, version del 9 nov 2026).
"""

